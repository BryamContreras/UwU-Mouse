import android.os.Bundle;
import android.os.Looper;
import android.os.Process;
import android.os.SystemClock;
import java.lang.reflect.Constructor;
import java.lang.reflect.Field;
import java.lang.reflect.InvocationTargetException;
import java.lang.reflect.Method;
import java.util.ArrayList;
import java.util.concurrent.ScheduledExecutorService;
import java.util.regex.PatternSyntaxException;

/** Read-only shell diagnostic for the window cache; never captures or injects input. */
public final class WindowCacheProbe {
    private WindowCacheProbe() { }

    public static void main(String[] args) {
        Object provider = null;
        int exitCode = 0;
        try {
            boolean stress = args.length == 1 && "--stress-20s".equals(args[0]);
            if (Process.myUid() != 2000 || !(args.length == 0 || stress)) {
                throw new SecurityException("Shell UID 2000 and optional --stress-20s required");
            }
            if (Looper.myLooper() == null) Looper.prepareMainLooper();
            Class.forName("android.app.ActivityThread").getMethod("systemMain").invoke(null);
            Class<?> type = Class.forName("dev.mobimapper.windowcontext.ShellWindowContextProvider");
            Constructor<?> constructor = type.getConstructor(long.class, long.class,
                    Class.forName("kotlin.jvm.functions.Function0"));
            provider = constructor.newInstance(stress ? 250L : 1000L, stress ? 750L : 2000L, null);
            Method snapshot = type.getMethod("snapshot");
            if (stress) {
                long started = SystemClock.uptimeMillis();
                while (SystemClock.uptimeMillis() - started < 20_000) {
                    printSnapshot("poll", (Bundle) snapshot.invoke(provider));
                    Thread.sleep(100);
                }
            } else {
                // Stop only this diagnostic instance's scheduler. Manual calls expose Throwables
                // that a ScheduledFuture would otherwise retain without printing a stack trace.
                Field worker = type.getDeclaredField("worker");
                worker.setAccessible(true);
                ((ScheduledExecutorService) worker.get(provider)).shutdownNow();
                Method refresh = type.getDeclaredMethod("refresh");
                refresh.setAccessible(true);
                printSnapshot("before", (Bundle) snapshot.invoke(provider));
                refresh.invoke(provider);
                printSnapshot("after_manual_refresh", (Bundle) snapshot.invoke(provider));
            }
        } catch (Throwable failure) {
            exitCode = 1;
            Throwable cause = unwrap(failure);
            System.err.println("{\"stage\":\"window_cache_probe\",\"errorType\":"
                    + quote(cause.getClass().getName()) + ",\"readOnly\":true}");
            // Linkage messages are generated by the VM and identify methods/classes, not
            // window titles. Other exception messages can contain metadata and are omitted.
            if (cause instanceof LinkageError) {
                System.err.println("{\"linkageMessage\":" + quote(cause.getMessage()) + "}");
            }
            if (cause instanceof PatternSyntaxException) {
                PatternSyntaxException pattern = (PatternSyntaxException) cause;
                System.err.println("{\"regexError\":" + quote(pattern.getDescription())
                        + ",\"index\":" + pattern.getIndex() + "}");
            }
            for (StackTraceElement frame : cause.getStackTrace()) {
                System.err.println("{\"frame\":" + quote(frame.toString()) + "}");
            }
        } finally {
            if (provider != null) {
                try { provider.getClass().getMethod("close").invoke(provider); }
                catch (Throwable closeFailure) {
                    exitCode = 1;
                    System.err.println("{\"closeErrorType\":" + quote(unwrap(closeFailure).getClass().getName()) + "}");
                }
            }
        }
        System.exit(exitCode);
    }

    private static void printSnapshot(String phase, Bundle snapshot) {
        @SuppressWarnings("deprecation")
        ArrayList<Bundle> windows = snapshot.getParcelableArrayList("windows");
        System.out.println("{\"phase\":" + quote(phase) + ",\"readOnly\":true,\"valid\":"
                + snapshot.getBoolean("valid") + ",\"error\":" + quote(snapshot.getString("error"))
                + ",\"capturedUptimeMs\":" + snapshot.getLong("capturedUptimeMs")
                + ",\"ageMs\":" + snapshot.getLong("ageMs")
                + ",\"count\":" + (windows == null ? 0 : windows.size()) + "}");
    }

    private static Throwable unwrap(Throwable failure) {
        while ((failure instanceof InvocationTargetException || failure instanceof ExceptionInInitializerError
                || failure instanceof NoClassDefFoundError) && failure.getCause() != null) {
            failure = failure.getCause();
        }
        return failure;
    }

    private static String quote(String text) {
        if (text == null) return "null";
        return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"")
                .replace("\r", "\\r").replace("\n", "\\n") + "\"";
    }
}
